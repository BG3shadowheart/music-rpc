"""Per-user installation: native messaging hosts, desktop entries, autostart.

Nothing here needs root: everything lives in the user's XDG directories, which is
what browsers require for a user-level native messaging host.
"""
from __future__ import annotations

import logging
import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

from . import autostart, control, native_install, paths
from .constants import APP_NAME, DEV_EXTENSION_ID
from .discord import find_ipc_sockets
from .extension_id import chrome_origin

log = logging.getLogger(__name__)

LAUNCHER_NAME = "music-rpc"
NATIVE_LAUNCHER_NAME = "music-rpc-native-host"


def default_bin_dir() -> Path:
    override = os.environ.get("MUSIC_RPC_BIN_DIR", "").strip()
    if override:
        return Path(override).expanduser()
    return Path.home() / ".local" / "bin"


def _installed_package_dir() -> str | None:
    """``PYTHONPATH`` value needed by launcher scripts.

    A source checkout needs the repository root; a distribution package keeps
    its vendored pure-Python dependencies in ``<root>/vendor``.
    """
    package_root = Path(__file__).resolve().parent.parent
    if "site-packages" in str(package_root) or "dist-packages" in str(package_root):
        return None
    parts = [str(package_root)]
    vendor = package_root / "vendor"
    if vendor.is_dir():
        parts.append(str(vendor))
    return os.pathsep.join(parts)


def _write_script(path: Path, body: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


def launcher_body(subcommand: str) -> str:
    python = sys.executable
    extra = ""
    package_root = _installed_package_dir()
    if package_root:
        extra = f'PYTHONPATH="{package_root}${{PYTHONPATH:+:$PYTHONPATH}}"\nexport PYTHONPATH\n'
    if getattr(sys, "frozen", False):
        exe = os.environ.get("MUSIC_RPC_EXECUTABLE") or sys.executable
        command = f'exec "{exe}" {subcommand} "$@"'
    else:
        command = f'exec "{python}" -m musicrpc {subcommand} "$@"'
    return (
        "#!/bin/sh\n"
        f"# Generated by {APP_NAME}. Do not edit: re-run 'music-rpc install'.\n"
        f"{extra}{command}\n"
    )


def ensure_launchers(bin_dir: Path | None = None) -> tuple[Path, Path]:
    """Create ``music-rpc`` and ``music-rpc-native-host`` wrapper scripts."""
    bin_dir = Path(bin_dir) if bin_dir else default_bin_dir()
    main = _write_script(bin_dir / LAUNCHER_NAME, launcher_body(""))
    native = _write_script(bin_dir / NATIVE_LAUNCHER_NAME, launcher_body("native-host"))
    return main, native


def resolve_host_path(bin_dir: Path | None = None) -> Path:
    """The executable a browser manifest should point at."""
    override = os.environ.get("MUSIC_RPC_NATIVE_HOST", "").strip()
    if override:
        return Path(override).expanduser()
    if getattr(sys, "frozen", False):
        return Path(sys.executable).resolve()
    _main, native = ensure_launchers(bin_dir)
    return native


def _origins(config, extra_ids) -> list[str]:
    origins = [origin for origin in config.extension_origins if origin]
    if DEV_EXTENSION_ID:
        origins.append(chrome_origin(DEV_EXTENSION_ID))
    for extension_id in extra_ids or []:
        origins.append(chrome_origin(extension_id))
    seen, unique = set(), []
    for origin in origins:
        if origin not in seen:
            seen.add(origin)
            unique.append(origin)
    return unique


def install(config, *, extension_ids=(), force_browsers=False, with_autostart=True,
            bin_dir: Path | None = None, host_path: Path | None = None,
            write_launchers: bool = True, write_menu_entry: bool = True) -> dict:
    bin_dir = Path(bin_dir) if bin_dir else default_bin_dir()
    if write_launchers or not host_path:
        main_launcher, native_launcher = ensure_launchers(bin_dir)
    else:
        main_launcher = bin_dir / LAUNCHER_NAME
        native_launcher = Path(host_path)
    host = Path(host_path) if host_path else resolve_host_path(bin_dir)
    origins = _origins(config, extension_ids)

    manifests = native_install.install(
        host, chrome_origins=origins, force=force_browsers)

    if with_autostart:
        autostart_path = autostart.install_autostart(
            [str(main_launcher), "run", "--background"])
    else:
        autostart.remove_autostart()
        autostart_path = None
    if write_menu_entry:
        menu_path = autostart.install_menu_entry([str(main_launcher), "run"])
    else:
        menu_path = None

    return {
        "host": str(host),
        "launcher": str(main_launcher),
        "native_launcher": str(native_launcher),
        "origins": origins,
        "manifests_installed": manifests["installed"],
        "manifests_skipped": manifests["skipped"],
        "autostart": str(autostart_path) if autostart_path else None,
        "menu_entry": str(menu_path) if menu_path else None,
        "discord_sockets": find_ipc_sockets(),
    }


def uninstall(*, purge: bool = False, remove_dir: Path | None = None) -> dict:
    removed_manifests = native_install.uninstall()
    had_autostart = autostart.remove_autostart()
    had_menu = autostart.remove_menu_entry()
    control.send_command("quit")

    removed_paths = []
    if purge:
        for target in (paths.config_dir(), paths.state_dir(), paths.cache_dir()):
            try:
                if target.exists():
                    shutil.rmtree(target)
                    removed_paths.append(str(target))
            except OSError as exc:
                log.warning("Could not remove %s: %s", target, exc)

    binaries = []
    for name in (LAUNCHER_NAME, NATIVE_LAUNCHER_NAME):
        candidate = (Path(remove_dir) if remove_dir else default_bin_dir()) / name
        try:
            if candidate.exists():
                candidate.unlink()
                binaries.append(str(candidate))
        except OSError as exc:
            log.warning("Could not remove %s: %s", candidate, exc)

    return {
        "manifests_removed": removed_manifests,
        "autostart_removed": had_autostart,
        "menu_entry_removed": had_menu,
        "purged": removed_paths,
        "binaries_removed": binaries,
    }


def self_command(subcommand: str, *extra: str) -> list[str]:
    """Command line that runs this same installation again."""
    if getattr(sys, "frozen", False):
        return [sys.executable, subcommand, *extra]
    executable = shutil.which(LAUNCHER_NAME)
    if executable:
        return [executable, subcommand, *extra]
    return [sys.executable, "-m", "musicrpc", subcommand, *extra]


def spawn_self(subcommand: str, *extra: str) -> subprocess.Popen | None:
    """Start a detached copy of this installation (settings window, daemon)."""
    try:
        return subprocess.Popen(
            self_command(subcommand, *extra),
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL, start_new_session=True, close_fds=True,
        )
    except Exception as exc:  # pragma: no cover - spawn failures
        log.warning("Could not start '%s': %s", subcommand, exc)
        return None
